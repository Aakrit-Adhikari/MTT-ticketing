import { PaymentMethod } from '@prisma/client';
import { IsDateString, IsEnum, IsOptional, IsString, IsUUID, Matches, MaxLength, MinLength } from 'class-validator';

export class RecordPaymentDto {
  /** NPR, up to 2 decimals, strictly positive. */
  @Matches(/^(?!0+(\.0+)?$)\d{1,10}(\.\d{1,2})?$/, { message: 'amount must be a positive number with at most 2 decimals' }) amount!: string;
  @IsEnum(PaymentMethod) method!: PaymentMethod;
  /** Bank / eSewa / Khalti transaction id or cheque number. The same one cannot be recorded twice. */
  @IsOptional() @IsString() @MinLength(3) @MaxLength(60) @Matches(/^[A-Za-z0-9 ._/-]+$/) reference?: string;
  @IsOptional() @IsDateString() receivedAt?: string;
  @IsOptional() @IsString() @MaxLength(300) note?: string;
  /** Generated by the form when it opens; a double click or retry then cannot record the payment twice. */
  @IsUUID() idempotencyKey!: string;
}

export class VoidPaymentDto {
  @IsString() @MinLength(3) @MaxLength(300) reason!: string;
}
